#[test]
fn locked_bank_rejects_feed_and_snapshot_without_consuming_status() {
    let mut io = Mock { locked_for: u32::MAX, ..Mock::default() };
    let mut delay = Delay::default();
    assert_eq!(feed(&mut io), Err(WatchdogError::Locked));
    assert_eq!(snapshot(&mut io, clock(32000), &mut delay), Err(WatchdogError::Locked));
    assert!(io.ops.is_empty());
    assert_eq!(delay.calls, 0);
}

#[test]
fn feed_only_reloads_and_stop_does_not_feed() {
    let mut io = Mock::default();
    assert_eq!(feed(&mut io), Ok(()));
    assert_eq!(io.ops, [Op::Restart]);
    io.ops.clear();
    stop(&mut io);
    assert_eq!(io.ops, [Op::Eoi, Op::Enable(false)]);
}

#[test]
fn back_to_back_snapshots_respect_device_rearm_and_reject_longer_stalls() {
    for gap in [0, 31_250, 62_500, 200_000, 250_000] {
        let time = Rc::new(Cell::new(0));
        let mut io = Mock { timeline: Some(time.clone()), rearm_ns: gap, ticks: 42, ..Mock::default() };
        let mut delay = Delay { timeline: Some(time), ..Delay::default() };
        assert_eq!(snapshot(&mut io, clock(32000), &mut delay).unwrap().ticks(), 42);
        feed(&mut io).unwrap(); // A control write does not reset the read-rearm window.
        let second = snapshot(&mut io, clock(32000), &mut delay);
        if gap <= 200_000 {
            assert_eq!(second.unwrap().ticks(), 42);
            assert_eq!(io.ops.iter().filter(|op| **op == Op::Count).count(), 2);
        } else {
            assert_eq!(second, Err(WatchdogError::SnapshotTimeout));
            assert_eq!(io.ops.iter().filter(|op| **op == Op::Count).count(), 1);
        }
    }
}

#[test]
fn snapshot_guard_rounds_up_two_input_periods_without_overflow() {
    for hz in [1, 31902, 32000, 2_000_001, u32::MAX] {
        let mut io = Mock::default();
        let mut delay = Delay::default();
        snapshot(&mut io, clock(hz), &mut delay).unwrap();
        let ns = u64::from(delay.durations[0]);
        assert!(ns * u64::from(hz) >= 2_000_000_000);
        assert!(ns >= 200_000);
        assert!(ns < 2_000_000_000u64.div_ceil(u64::from(hz)).max(200_000) + 1000);
    }
}
