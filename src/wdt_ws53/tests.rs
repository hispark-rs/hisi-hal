//! Fault-injected operation tests, not a silicon counter/reset model.
use super::*;
use std::vec::Vec;
use std::{cell::Cell, rc::Rc};

#[derive(Debug, PartialEq, Eq)]
enum Op {
    Unlock,
    Eoi,
    Enable(bool),
    Configure,
    Mode(WatchdogMode),
    Load(u32),
    Restart,
    Request,
    Count,
}
#[derive(Default)]
struct Mock {
    ops: Vec<Op>,
    lock_reads: u32,
    ready_reads: u32,
    locked_for: u32,
    invalid_for: u32,
    ticks: u32,
    timeline: Option<Rc<Cell<u64>>>,
    next_request_ns: u64,
    rearm_ns: u64,
    accepted: bool,
}
impl Registers for Mock {
    fn unlock(&mut self) {
        self.ops.push(Op::Unlock);
    }
    fn locked(&mut self) -> bool {
        self.lock_reads += 1;
        self.lock_reads <= self.locked_for
    }
    fn clear_interrupt(&mut self) {
        self.ops.push(Op::Eoi);
    }
    fn enable(&mut self, value: bool) {
        self.ops.push(Op::Enable(value));
    }
    fn configure(&mut self) {
        self.ops.push(Op::Configure);
    }
    fn mode(&mut self, mode: WatchdogMode) {
        self.ops.push(Op::Mode(mode));
    }
    fn load(&mut self, value: u32) {
        self.ops.push(Op::Load(value));
    }
    fn restart(&mut self) {
        self.ops.push(Op::Restart);
    }
    fn request_snapshot(&mut self) {
        self.ops.push(Op::Request);
        if let Some(time) = &self.timeline {
            self.accepted = time.get() >= self.next_request_ns;
        }
    }
    fn snapshot_valid(&mut self) -> bool {
        self.ready_reads += 1;
        if self.timeline.is_some() {
            return self.accepted;
        }
        self.ready_reads > self.invalid_for
    }
    fn count(&mut self) -> u32 {
        if let Some(time) = &self.timeline {
            assert!(self.accepted, "invalid snapshot must not be consumed");
            self.accepted = false;
            self.next_request_ns = time.get() + self.rearm_ns;
        }
        self.ops.push(Op::Count);
        self.ticks
    }
}
#[derive(Default)]
struct Delay {
    calls: u32,
    durations: Vec<u32>,
    timeline: Option<Rc<Cell<u64>>>,
}
impl DelayNs for Delay {
    fn delay_ns(&mut self, ns: u32) {
        self.durations.push(ns);
        self.calls += 1;
        if let Some(time) = &self.timeline {
            time.set(time.get() + u64::from(ns));
        }
    }
}
fn clock(hz: u32) -> NonZeroU32 {
    NonZeroU32::new(hz).unwrap()
}

#[test]
fn seconds_conversion_preserves_sdk_boundaries_without_wrap() {
    let mode = WatchdogMode::Reset;
    assert!(Config::from_seconds(clock(32000), 0, mode).is_none());
    assert!(Config::from_seconds(clock(1), 254, mode).is_none());
    assert_eq!(Config::from_seconds(clock(1), 255, mode).unwrap().load_upper_bits(), 0);
    assert_eq!(Config::from_seconds(clock(1), 256, mode).unwrap().load_upper_bits(), 1);
    assert_eq!(Config::from_seconds(clock(1), u32::MAX, mode).unwrap().load_upper_bits(), 0xffffff);
    assert!(Config::from_seconds(clock(2), 0x80000000, mode).is_none());
    assert!(Config::from_seconds(clock(u32::MAX), u32::MAX, mode).is_none());
    let config = Config::from_seconds(clock(32000), 64, mode).unwrap();
    assert_eq!(config.load_upper_bits(), 8000);
    assert_eq!(config.clock_hz().get(), 32000);
    assert_eq!(config.requested_seconds().get(), 64);
    // FPGA's odd input frequency must preserve the SDK's discarded low byte.
    assert_eq!(Config::from_seconds(clock(31902), 2, mode).unwrap().load_upper_bits(), 249);
}

proptest::proptest! {
    #[test]
    fn conversion_matches_wide_reference(hz in 1u32..=u32::MAX, seconds in proptest::num::u32::ANY) {
        let product = u64::from(hz) * u64::from(seconds);
        let value = Config::from_seconds(clock(hz), seconds, WatchdogMode::InterruptThenReset);
        proptest::prop_assert_eq!(value.is_some(), (255..=u64::from(u32::MAX)).contains(&product));
        if let Some(value) = value {
            proptest::prop_assert_eq!(u64::from(value.load_upper_bits()) * 256, product - product % 256);
            proptest::prop_assert_eq!(value.mode(), WatchdogMode::InterruptThenReset);
        }
    }
}

#[test]
fn both_modes_stop_before_configuration_and_feed_after_enabling() {
    // Generated by compiling the pinned vendor C control flow with traced IO,
    // rather than a second hand-written copy of the Rust operation sequence.
    let sdk = [include_str!("sdk-start-0.txt"), include_str!("sdk-start-1.txt")];
    for (index, mode) in [WatchdogMode::Reset, WatchdogMode::InterruptThenReset].into_iter().enumerate() {
        let mut io = Mock { locked_for: 3, ..Mock::default() };
        let mut delay = Delay::default();
        let config = Config::from_seconds(clock(32000), 64, mode).unwrap();
        assert_eq!(start(&mut io, config, &mut delay), Ok(()));
        assert_eq!(delay.calls, 3);
        let trace: std::string::String = io.ops.iter().map(|op| std::format!("{op:?}\n")).collect();
        assert_eq!(trace, sdk[index]);
    }
}

#[test]
fn failed_unlock_never_acknowledges_or_changes_watchdog() {
    let mut io = Mock { locked_for: u32::MAX, ..Mock::default() };
    let mut delay = Delay::default();
    let config = Config::from_seconds(clock(32000), 64, WatchdogMode::Reset).unwrap();
    assert_eq!(start(&mut io, config, &mut delay), Err(WatchdogError::UnlockTimeout));
    assert_eq!(io.ops, [Op::Unlock]);
    assert_eq!(io.lock_reads, 2001);
    assert_eq!(delay.calls, 2000);
}

#[test]
fn snapshot_timeout_never_reads_stale_counter_or_feeds() {
    let mut io = Mock { invalid_for: u32::MAX, ticks: 1234, ..Mock::default() };
    let mut delay = Delay::default();
    assert_eq!(snapshot(&mut io, clock(32000), &mut delay), Err(WatchdogError::SnapshotTimeout));
    assert_eq!(io.ops, [Op::Request]);
    assert_eq!(io.ready_reads, 2001);
    assert_eq!(delay.calls, 2001);
    assert_eq!(delay.durations[0], 200_000);
    assert!(delay.durations[1..].iter().all(|ns| *ns == 1_000));
}

#[test]
fn snapshots_distinguish_zero_and_last_poll_success_from_failure() {
    for (ticks, invalid_for) in [(0, 0), (123456, 7), (u32::MAX, 2000)] {
        let mut io = Mock { ticks, invalid_for, ..Mock::default() };
        let mut delay = Delay::default();
        let value = snapshot(&mut io, clock(1), &mut delay).unwrap();
        assert_eq!(value.ticks(), ticks);
        assert_eq!(value.micros(), u64::from(ticks) * 1_000_000);
        assert_eq!(io.ops, [Op::Request, Op::Count]);
        assert_eq!(delay.calls, invalid_for + 1);
        assert_eq!(delay.durations[0], 2_000_000_000);
    }
}

